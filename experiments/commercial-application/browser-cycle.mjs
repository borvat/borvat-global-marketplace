// Synthetic workbench only. Supply an installed Playwright module and a local browser.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(resolve(process.env.PLAYWRIGHT_MODULE)));
const out = resolve(process.env.BROWSER_EVIDENCE_DIR);
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true });
const results = [];
try {
  for (const width of [1440, 390, 320]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } });
    const errors = [], external = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.route('**/*', route => {
      const url = new URL(route.request().url());
      if (url.hostname === '127.0.0.1' && url.port === '4178') return route.continue();
      external.push(url.origin); return route.abort();
    });
    const button = name => page.getByRole('button', { name, exact: true });
    const layout = async name => {
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${name}: horizontal overflow at ${width}`);
      await page.screenshot({ path: `${out}/${width}-${name}.png`, fullPage: true });
    };
    await page.goto('http://127.0.0.1:4178/workbench');
    await page.getByTestId('product').first().waitFor();
    await layout('catalog');
    await page.getByLabel('Zoek producten', { exact: true }).fill('no-synthetic-match');
    await page.getByText('Geen producten gevonden.', { exact: false }).waitFor();
    assert.equal(await page.getByTestId('product').count(), 0);
    await page.getByLabel('Zoek producten', { exact: true }).fill('');
    await page.getByLabel('Categorie', { exact: true }).selectOption('Tuin');
    assert.equal(await page.getByTestId('product').count(), 3);
    await page.getByLabel('Categorie', { exact: true }).selectOption('Alles');
    await page.getByLabel('Sorteer', { exact: true }).selectOption('price');
    assert.match(await page.getByTestId('product').first().innerText(), /plantenpot/);
    await button('Voeg toe · Voorbeeldwinkel A').click();
    await button('Voeg toe · Voorbeeldwinkel B').click();
    await button('Mandje (2)').click();
    await page.getByLabel('Aantal · Voorbeeldwinkel A', { exact: true }).fill('2');
    await button('Mandje (3)').waitFor();
    assert.equal(await button('Betalen niet beschikbaar').isDisabled(), true);
    await layout('cart');
    await button('Bewaar demo-aanvraag').click();
    assert.equal(await page.getByTestId('order').count(), 1);
    assert.match(await page.getByTestId('order').innerText(), /2 ×/);
    await button('Verkoper').click();
    await button('Markeer demo als voorbereid').click();
    await page.getByLabel('Voorbeeldwinkel (geen accountwissel)', { exact: true }).selectOption('demo-b');
    await button('Markeer demo als voorbereid').click();
    await button('Koper').click();
    assert.match(await page.getByTestId('order').innerText(), /Demo voorbereid/);
    await layout('prepared-request');
    await button('Verkoper').click();
    await page.getByLabel('Voorbeeldwinkel (geen accountwissel)', { exact: true }).selectOption('demo-a');
    const price = page.getByLabel('Voorbeeldprijs in euro', { exact: true }).first();
    await price.fill('not-a-price');
    await button('Bewaar concept').first().click();
    await page.getByRole('alert').waitFor();
    await price.fill('42.50');
    await button('Bewaar concept').first().click();
    await button('Vraag beoordeling').first().click();
    await layout('seller');
    await button('Beheer').click();
    await page.getByRole('region', { name: 'Aanbodbeoordeling' }).locator('div.rounded-xl').filter({ hasText: '42,50' }).getByRole('button', { name: 'Publiceer in demo', exact: true }).click();
    assert.equal(await button('Publiceer in demo').count(), 1); // Original review fixture remains.
    await layout('admin');
    await button('Koper').click();
    assert.doesNotMatch(await page.getByTestId('order').innerText(), /42,50/);
    await button('Producten').click();
    await page.getByRole('complementary').getByText(/42,50/).waitFor();
    await button('Reset demo').click();
    await button('Aanvragen').click();
    assert.equal(await page.getByTestId('order').count(), 0);
    await page.reload();
    await button('Mandje (0)').waitFor();
    // Remove each line through the actual cart controls; empty carts cannot submit.
    await button('Voeg toe · Voorbeeldwinkel A').click();
    await button('Voeg toe · Voorbeeldwinkel B').click();
    await button('Mandje (2)').click();
    await button('Verwijder · Voorbeeldwinkel A').click();
    await button('Mandje (1)').waitFor();
    assert.equal(await page.getByLabel('Aantal · Voorbeeldwinkel B', { exact: true }).inputValue(), '1');
    await button('Verwijder · Voorbeeldwinkel B').click();
    await button('Mandje (0)').waitFor();
    assert.equal(await button('Bewaar demo-aanvraag').isDisabled(), true);

    // A cart becomes unavailable while its seller offer is drafted/reviewed.
    await button('Producten').click();
    await button('Voeg toe · Voorbeeldwinkel A').click();
    await button('Verkoper').click();
    await page.getByLabel('Voorbeeldprijs in euro', { exact: true }).first().fill('123.45');
    await button('Bewaar concept').first().click();
    await button('Koper').click();
    await button('Mandje (1)').click();
    await page.getByRole('alert').waitFor();
    assert.equal(await button('Bewaar demo-aanvraag').isDisabled(), true);
    await layout('stale-cart');
    await button('Verkoper').click();
    await button('Vraag beoordeling').first().click();
    await button('Beheer').click();
    const reviewed = () => page.getByRole('region', { name: 'Aanbodbeoordeling' }).locator('div.rounded-xl').filter({ hasText: '123,45' });
    await reviewed().getByRole('button', { name: 'Terug naar concept', exact: true }).click();
    assert.equal(await reviewed().count(), 0);
    await button('Koper').click();
    assert.equal(await button('Bewaar demo-aanvraag').isDisabled(), true);
    await button('Verkoper').click();
    await button('Vraag beoordeling').first().click();
    await button('Beheer').click();
    await reviewed().getByRole('button', { name: 'Publiceer in demo', exact: true }).click();
    await button('Koper').click();
    assert.equal(await page.getByRole('alert').count(), 0);
    assert.match(await page.getByRole('region', { name: 'Winkelmandje' }).innerText(), /123,45/);
    await button('Bewaar demo-aanvraag').dblclick();
    assert.equal(await page.getByTestId('order').count(), 1);
    await button('Mandje (0)').click();
    assert.equal(await button('Bewaar demo-aanvraag').isDisabled(), true);
    await button('Verkoper').click();
    await button('Markeer demo als voorbereid').dblclick();
    assert.equal(await button('Markeer demo als voorbereid').count(), 0);
    await button('Koper').click();
    await button('Aanvragen').click();
    assert.equal(await page.getByTestId('order').count(), 1);
    assert.match(await page.getByTestId('order').innerText(), /Demo voorbereid/);
    await layout('repeated-actions');

    // Reload is the documented interruption boundary: all memory-only work is discarded.
    await page.reload();
    await button('Mandje (0)').waitFor();
    await page.keyboard.press('Tab');
    assert.equal(await button('Koper').evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Tab');
    assert.equal(await button('Verkoper').evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Enter');
    await page.getByRole('heading', { name: 'Verkoperscentrum', exact: true }).waitFor();
    await page.keyboard.press('Tab');
    await page.keyboard.press('Space');
    await page.getByRole('heading', { name: 'Beheer van het voorbeeld', exact: true }).waitFor();
    await page.keyboard.press('Shift+Tab');
    await page.keyboard.press('Enter');
    await page.getByRole('heading', { name: 'Verkoperscentrum', exact: true }).waitFor();
    const resetPrice = page.getByLabel('Voorbeeldprijs in euro', { exact: true }).first();
    const originalPrice = await resetPrice.inputValue();
    await resetPrice.fill('17.00');
    await button('Reset demo').dblclick();
    assert.equal(await resetPrice.inputValue(), originalPrice, 'reset must discard unsaved seller input');
    await resetPrice.fill('18.00');
    await button('Bewaar concept').first().click();
    await page.reload();
    await button('Verkoper').click();
    assert.equal(await resetPrice.inputValue(), originalPrice, 'reload discards saved demo edits');
    await button('Koper').click();
    await button('Voeg toe · Voorbeeldwinkel A').click();
    await button('Mandje (1)').click();
    const quantity = page.getByLabel('Aantal · Voorbeeldwinkel A', { exact: true });
    await quantity.focus();
    await page.keyboard.press('ControlOrMeta+A');
    await page.keyboard.press('Backspace');
    assert.equal(await quantity.count(), 1, 'clearing quantity must not silently remove the cart line');
    await quantity.fill('2');
    await button('Mandje (2)').waitFor();
    await quantity.fill('');
    await page.keyboard.press('Tab');
    assert.equal(await quantity.inputValue(), '2', 'leaving an empty edit restores the last valid quantity');
    await quantity.fill('99');
    await page.getByRole('alert').waitFor();
    assert.equal(await quantity.inputValue(), '2', 'invalid quantity preserves the last valid quantity');
    await layout('keyboard-cart');
    await button('Verkoper').click();
    await page.getByLabel('Voorbeeldprijs in euro', { exact: true }).first().fill('19.00');
    await button('Bewaar concept').first().click();
    await button('Koper').click();
    assert.equal(await button('Bewaar demo-aanvraag').isDisabled(), true);
    await button('Verwijder · Voorbeeldwinkel A').click();
    await button('Mandje (0)').waitFor();
    assert.equal(await page.getByRole('alert').count(), 0, 'stale offer can still be removed');
    assert.equal(await button('Bewaar demo-aanvraag').isDisabled(), true);
    await page.reload();
    await button('Mandje (0)').click();
    assert.equal(await button('Bewaar demo-aanvraag').isDisabled(), true);
    assert.deepEqual(errors, []);
    assert.deepEqual(external, []);
    results.push({ width, status: 'PASS', extendedCases: ['cart-removal', 'stale-cart', 'stale-cart-removal', 'return-to-draft', 'republish-cart', 'double-submit', 'double-prepare', 'keyboard-navigation', 'reset-unsaved-input', 'reload-draft-and-cart', 'keyboard-quantity'], pageErrors: errors, externalRequests: external });
    await page.close();
  }
} catch (error) {
  results.push({ status: 'FAIL', error: error.message });
  throw error;
} finally {
  await writeFile(`${out}/results.json`, JSON.stringify({ browser: browser.version(), scope: 'synthetic commercial preview; not full app or native integration', results }, null, 2));
  await browser.close();
}
