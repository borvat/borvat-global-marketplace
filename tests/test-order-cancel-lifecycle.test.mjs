import {test} from "node:test";
import assert from "node:assert/strict";
import {createTestOrder} from "../services/test-order-service.mjs";
import {cancelDraftTestOrder} from "../services/test-cancel-draft-order.mjs";
const id=n=>"00000000-0000-4000-8000-"+String(n).padStart(12,"0");
test("draft lifecycle: reserve, replay, cancel, no double restoration or cancelled-order replay",async()=>{
 const buyer=id(100),seller=id(11),offer=id(1),state={stock:4,order:null,sub:null,line:null,events:[]};
 const pool={async connect(){let before;return {release(){},async query(sql,args=[]){
  if(sql.startsWith("BEGIN")){before=structuredClone(state);return {rows:[]}};
  if(sql==="COMMIT")return {rows:[]};
  if(sql==="ROLLBACK"){Object.assign(state,before);return {rows:[]}};
  if(sql.startsWith("SELECT pg_advisory_xact_lock"))return {rows:[]};
  if(sql.includes("FROM borvat.buyer_orders WHERE buyer_id"))return {rows:state.order&&state.order.key===args[1]?[{id:state.order.id,request_hash:state.order.hash,total_minor:state.order.total,state:state.order.state}]:[]};
  if(sql.includes("FROM borvat.offers o JOIN"))return {rows:[{id:offer,seller_id:seller,price_minor:"12100",stock:state.stock,market:"NL",currency:"EUR",status:"published",seller_status:"approved",product_status:"approved"}]};
  if(sql.startsWith("SELECT 1 FROM borvat.risk_cases"))return {rows:[]};
  if(sql.startsWith("INSERT INTO borvat.buyer_orders")){state.order={id:args[0],buyer:args[1],key:args[2],hash:args[3],total:args[4],state:"draft"};return {rowCount:1}};
  if(sql.startsWith("INSERT INTO borvat.seller_orders")){state.sub={id:args[0],state:"created"};return {rowCount:1}};
  if(sql.startsWith("UPDATE borvat.offers SET stock=stock-1")){if(state.stock<1)return {rowCount:0};state.stock--;return {rowCount:1}};
  if(sql.startsWith("INSERT INTO borvat.order_lines")){state.line={id:args[0],quantity:1};return {rowCount:1}};
  if(sql.startsWith("SELECT id,state FROM borvat.buyer_orders"))return {rows:state.order?.id===args[0]&&state.order?.buyer===args[1]?[{id:state.order.id,state:state.order.state}]:[]};
  if(sql.startsWith("SELECT id,seller_id,state FROM borvat.seller_orders"))return {rows:[{id:state.sub.id,seller_id:seller,state:state.sub.state}]};
  if(sql.startsWith("SELECT l.id,l.offer_id,l.quantity"))return {rows:[{id:state.line.id,offer_id:offer,quantity:state.line.quantity,seller_id:seller}]};
  if(sql.startsWith("SELECT id,seller_id,stock FROM borvat.offers"))return {rows:[{id:offer,seller_id:seller,stock:state.stock}]};
  if(sql.startsWith("UPDATE borvat.offers SET stock=stock+")){state.stock+=args[1];return {rowCount:1}};
  if(sql.startsWith("UPDATE borvat.seller_orders")){state.sub.state="cancelled";return {rowCount:1}};
  if(sql.startsWith("UPDATE borvat.buyer_orders")){state.order.state="cancelled";return {rowCount:1}};
  if(sql.startsWith("INSERT INTO borvat.outbox_events")){state.events.push(sql.includes("cancelled")?"cancelled":"created");return {rowCount:1}};
  throw new Error("UNMOCKED SQL "+sql);
 }}}};
 const auth={authorizeBuyer:async()=>true},req={buyerId:buyer,requestKey:"lifecycle-e2e-001",offerIds:[offer]};
 const first=await createTestOrder(pool,req,auth);
 assert.equal(state.stock,3);assert.equal(first.replayed,false);
 assert.equal((await createTestOrder(pool,req,auth)).replayed,true);assert.equal(state.stock,3);
 const cancel=await cancelDraftTestOrder(pool,{buyerId:buyer,orderId:first.orderId},auth);
 assert.equal(cancel.restoredLines,1);assert.equal(state.stock,4);
 assert.equal((await cancelDraftTestOrder(pool,{buyerId:buyer,orderId:first.orderId},auth)).replayed,true);
 assert.equal(state.stock,4);
 await assert.rejects(createTestOrder(pool,req,auth),/ORDER_ALREADY_CANCELLED/);
 assert.equal(state.stock,4);assert.deepEqual(state.events,["created","cancelled"]);
});
